// Merge missing Arabic keys
let added = 0;
for (const [namespace, keys] of Object.entries(arTranslations)) {
  if (!ar[namespace]) {
    ar[namespace] = {};
  }
  for (const [key, value] of Object.entries(keys)) {
    if (!ar[namespace][key]) {
      ar[namespace][key] = value;
      added++;
    }
  }
}

writeFileSync(arPath, JSON.stringify(ar, null, 2) + "\n", "utf-8");
console.log(`Added ${added} missing Arabic translation keys.`);

// Report remaining missing keys
let missing = 0;
for (const [namespace, enKeys] of Object.entries(en)) {
  if (typeof enKeys !== "object" || enKeys === null) continue;
  for (const key of Object.keys(enKeys)) {
    if (!ar[namespace]?.[key]) {
      console.log(`  MISSING: ${namespace}.${key}`);
      missing++;
    }
  }
}
if (missing > 0) {
  console.log(`\nStill ${missing} keys missing from Arabic.`);
} else {
  console.log("\nAll English keys have Arabic translations.");
}
